/**
 * Reproduce the critical assets without changing the artwork or font family.
 * Run explicitly after upgrading @fontsource/poppins or editing the two source images.
 * Content-addressed filenames allow immutable caching without stale replacements.
 * Commit the generated public files, CSS and manifests together. Next serves the
 * checked-in assets directly; the asset tests verify their hashes and font CSS
 * against the installed package, so deployments do not need a Sharp prebuild.
 */
import { createHash } from "node:crypto";
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = process.cwd();
const digest = (bytes) => createHash("sha256").update(bytes).digest("hex").slice(0, 12);
const fontDir = path.join(root, "public/assets/fonts/poppins");
const artDir = path.join(root, "public/assets/demos/word-heroes");
const backgroundDir = path.join(root, "public/assets/backgrounds");
await Promise.all([mkdir(fontDir, { recursive: true }), mkdir(artDir, { recursive: true }), mkdir(backgroundDir, { recursive: true })]);

const fonts = {};
const styles = ["/* Generated by scripts/build-word-game-critical-assets.mjs. */"];
for (const weight of [400, 500, 600, 700, 800, 900]) {
  let css = await readFile(path.join(root, `node_modules/@fontsource/poppins/${weight}.css`), "utf8");
  for (const match of css.matchAll(/\.\/files\/([^)]+)/g)) {
    const filename = match[1];
    const source = path.join(root, "node_modules/@fontsource/poppins/files", filename);
    const bytes = await readFile(source);
    const ext = path.extname(filename);
    const target = `${path.basename(filename, ext)}.${digest(bytes)}${ext}`;
    const url = `/assets/fonts/poppins/${target}`;
    await copyFile(source, path.join(fontDir, target));
    css = css.replace(`./files/${filename}`, url);
    if (ext === ".woff2") fonts[filename.replace("-normal.woff2", "")] = url;
  }
  styles.push(css.trim());
}
await copyFile(path.join(root, "node_modules/@fontsource/poppins/LICENSE"), path.join(fontDir, "LICENSE.txt"));
await writeFile(path.join(root, "src/styles/poppins.css"), `${styles.join("\n\n")}\n`);
await writeFile(path.join(root, "src/lib/word-game-font-assets.json"), `${JSON.stringify(fonts, null, 2)}\n`);

const heroes = {};
// Keep the original aspect ratio; no enlarged source or artwork redesign.
for (const [slug, sourceName] of [["name-chain", "son-harfle"], ["shared-player", "ortak-futbolcu"]]) {
  const source = path.join(root, `public/assets/demos/game-modes/${sourceName}.webp`);
  const avifQuality = 35;
  const variants = {};
  for (const format of ["avif", "webp"]) {
    variants[format] = {};
    for (const width of [384, 640, 672, 720, 750, 1080, 1200, 1600]) {
      const image = sharp(source).resize({ width });
      // Same source artwork and geometry. Both q35 variants passed the recorded
      // phone/desktop visual and byte prototypes; every WebP stays q60.
      // Keep previous immutable outputs so reverting the manifest is sufficient.
      const bytes = await (format === "avif" ? image.avif({ quality: avifQuality, effort: 9, chromaSubsampling: "4:2:0" }) : image.webp({ quality: 60 })).toBuffer();
      const filename = `${sourceName}-${width}.${digest(bytes)}.${format}`;
      await writeFile(path.join(artDir, filename), bytes);
      variants[format][width] = `/assets/demos/word-heroes/${filename}`;
    }
  }
  heroes[slug] = variants;
}
await writeFile(path.join(root, "src/features/demos/word-hero-assets.json"), `${JSON.stringify(heroes, null, 2)}\n`);
// The existing translucent stadium pattern keeps its full dimensions and alpha.
// CSS image-set serves AVIF only when supported; the original WebP is retained.
const background = await sharp(path.join(root, "public/assets/bg-pattern.webp")).avif({ quality: 40, effort: 6 }).toBuffer();
const backgroundName = `bg-pattern.${digest(background)}.avif`;
await writeFile(path.join(backgroundDir, backgroundName), background);
await writeFile(path.join(root, "src/lib/app-background-assets.json"), `${JSON.stringify({ patternAvif: `/assets/backgrounds/${backgroundName}` }, null, 2)}\n`);
console.log("Generated all existing Poppins subsets/weights, two responsive word-game heroes and the stadium background.");
