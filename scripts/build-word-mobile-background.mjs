/** Generate a same-art, density-safe background for compact word landing pages. */
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = process.cwd();
const source = await readFile(path.join(root, "public/assets/bg-pattern.webp"));
const image = await sharp(source).resize({ width: 1080, withoutEnlargement: true })
  .avif({ quality: 40, effort: 9, chromaSubsampling: "4:2:0" }).toBuffer({ resolveWithObject: true });
const sha256 = bytes => createHash("sha256").update(bytes).digest("hex");
const href = `/assets/backgrounds/bg-pattern-mobile-1080.${sha256(image.data).slice(0, 12)}.avif`;
await mkdir(path.join(root, "public/assets/backgrounds"), { recursive: true });
await writeFile(path.join(root, "public", href), image.data);
await writeFile(path.join(root, "src/lib/word-mobile-background-assets.json"), JSON.stringify({
  href, width: image.info.width, height: image.info.height, bytes: image.data.length, sourceSHA256: sha256(source),
}, null, 2) + "\n");
await writeFile(path.join(root, "src/styles/word-mobile-background.css"), `/* Generated by scripts/build-word-mobile-background.mjs. */
/* 1080x1907 covers these CSS bounds at 2x without upscaling. */
@media (max-width: 540px) and (max-height: 950px) and (max-resolution: 2dppx) {
  body[data-qb-word-background="1"] .qb-word-mobile-background {
    --qb-word-background: image-set(url('${href}') type('image/avif'), url('/assets/bg-pattern.webp') type('image/webp'));
  }
}
`);
console.log(JSON.stringify({ href, bytes: image.data.length, width: image.info.width, height: image.info.height }));
