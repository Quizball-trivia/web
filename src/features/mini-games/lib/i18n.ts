const DICTS: Partial<Record<MiniLocale, Record<string, string>>> = { ka: KA, es: ES, tr: TR, ru: RU, pt: PT, de: DE };

export function useMiniLocale(): MiniLocale {
  const { locale } = useLocale();
  return locale;
}

/** t('Question {n} / {total}', { n: 1, total: 5 }) — EN key, {slot} substitution. */
export function useMiniT() {
  const locale = useMiniLocale();
  return useCallback(
    (key: string, vars?: Record<string, string | number>) => {
      let out = DICTS[locale]?.[key] ?? key;
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          out = out.split(`{${k}}`).join(String(v));
        }
      }
      return out;
    },
    [locale],
  );
}
