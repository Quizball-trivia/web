export function getDemoAuctionRoster(locale: Locale): Footballer[] {
  if (locale !== "ka") return FOOTBALLERS;
  return FOOTBALLERS.map((footballer) => {
    const ka = KA_ROSTER[footballer.id];
    if (!ka) return footballer;
    return {
      ...footballer,
      name: ka.name,
      nationality: ka.nationality,
      clues: ka.clues,
    };
  });
}
