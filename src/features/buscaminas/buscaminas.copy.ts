export const buscaminasCopy = (locale: string): Copy => (locale === "es" ? es : locale === "ka" ? ka : locale === "tr" ? tr : locale === "ru" ? ru : locale === "pt" ? pt : locale === "de" ? de : en);
/** Prompts ship in es/en and, from content v2, ka/tr/ru/pt; a missing locale falls back to English. */
export const promptFor = (prompt: { es: string; en: string; ka?: string; tr?: string; ru?: string; pt?: string; de?: string }, locale: string) =>
  (locale === "es" ? prompt.es : locale === "ka" ? prompt.ka : locale === "tr" ? prompt.tr : locale === "ru" ? prompt.ru : locale === "pt" ? prompt.pt : locale === "de" ? prompt.de : undefined) ?? prompt.en;
