export type TextGrid = {
  cols: number;
  rows: number;
  on: (c: number, r: number) => boolean;
};

/** Rasterise a line of text; width is 6 cells per character minus the trailing gap. */
export function textToGrid(text: string): TextGrid {
  const chars = text.toUpperCase().split("");
  const cols = Math.max(0, chars.length * (GLYPH_W + GAP) - GAP);
  return {
    cols,
    rows: GLYPH_H,
    on(c, r) {
      if (r < 0 || r >= GLYPH_H || c < 0 || c >= cols) return false;
      const i = Math.floor(c / (GLYPH_W + GAP));
      const gc = c - i * (GLYPH_W + GAP);
      if (gc >= GLYPH_W) return false;
      const glyph = GLYPHS[chars[i]] ?? GLYPHS[" "];
      return glyph[r][gc] === "#";
    },
  };
}

/** Longest text that fits a wall of the given width, in characters. */
export function maxCharsFor(cols: number): number {
  return Math.floor((cols + GAP) / (GLYPH_W + GAP));
}
